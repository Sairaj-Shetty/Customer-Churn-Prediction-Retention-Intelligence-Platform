"""Prediction drift from the existing prediction audit log.

Why this is separate from feature drift
---------------------------------------
Feature drift needs aggregate-only collection because storing feature vectors
would mean storing customer records. Predictions are different: the audit table
already holds ``churn_probability``, ``predicted_class`` and ``risk_band`` per
prediction, at full row-level fidelity, and none of that is a customer record.

That makes prediction drift the one place where a genuine row-level comparison is
available at zero additional privacy cost — and it is the drift that matters most
operationally, because it is the output distribution the business actually sees.

Reference distribution
----------------------
Generated by scoring the **validation split** with the **frozen calibrated
artifact**. Two things follow from that:

* It is the same model that is serving, so a comparison measures the world
  changing rather than the model changing.
* It is generated once and cached, not recomputed from live data, so the
  reference cannot drift along with production — which would hide the very
  change we are trying to detect.

The validation split is used rather than train because the model was selected and
its threshold optimised on validation, so its prediction distribution there is the
one the frozen serving configuration actually produced. Train predictions would be
optimistically shifted by fitting.

What this cannot detect
-----------------------
Performance drift. Without ground-truth churn outcomes arriving later, nobody can
say whether the predictions are still *correct* — only whether their distribution
has moved. That distinction is stated in the report rather than glossed over.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from sqlalchemy import select
from sqlalchemy.orm import Session

from churn.db.models import Prediction
from churn.logging_utils import get_logger
from churn.monitoring.drift import (
    benjamini_hochberg,
    chi_square_p_value,
    jensen_shannon_distance,
    population_stability_index,
)

logger = get_logger(__name__)

#: Fixed probability bins. Frozen so production and reference use identical
#: edges — the same reasoning as the feature schema, and the reason this is a
#: constant rather than something derived per-run.
PROBABILITY_BINS: tuple[float, ...] = (
    0.0,
    0.05,
    0.10,
    0.20,
    0.30,
    0.40,
    0.50,
    0.60,
    0.70,
    0.80,
    0.90,
    0.95,
    1.0001,
)

REFERENCE_DIR = Path("artifacts/monitoring")


@dataclass
class PredictionDriftResult:
    """Prediction-distribution comparison for one window."""

    status: str
    generated_at_utc: str
    model_version: str
    observations: int = 0
    min_observations: int = 0
    window_start: str | None = None
    window_end: str | None = None
    #: Probability histogram comparison.
    probability_psi: float = 0.0
    probability_js: float = 0.0
    probability_p_value: float | None = None
    #: Risk-band distribution comparison.
    band_js: float = 0.0
    band_p_value: float | None = None
    #: Positive-rate shift, the number a business reader looks at first.
    reference_positive_rate: float = 0.0
    production_positive_rate: float = 0.0
    reference_mean_probability: float = 0.0
    production_mean_probability: float = 0.0
    drifted: bool = False
    detail: str = ""
    notes: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "status": self.status,
            "generated_at_utc": self.generated_at_utc,
            "model_version": self.model_version,
            "window": {"start": self.window_start, "end": self.window_end},
            "observations": self.observations,
            "min_observations": self.min_observations,
            "drifted": self.drifted,
            "probability": {
                "psi": round(self.probability_psi, 6),
                "jensen_shannon": round(self.probability_js, 6),
                "p_value": None
                if self.probability_p_value is None
                else float(f"{self.probability_p_value:.6g}"),
                "reference_mean": round(self.reference_mean_probability, 6),
                "production_mean": round(self.production_mean_probability, 6),
            },
            "risk_band": {
                "jensen_shannon": round(self.band_js, 6),
                "p_value": None if self.band_p_value is None else float(f"{self.band_p_value:.6g}"),
            },
            "positive_rate": {
                "reference": round(self.reference_positive_rate, 6),
                "production": round(self.production_positive_rate, 6),
                "delta": round(self.production_positive_rate - self.reference_positive_rate, 6),
            },
            "detail": self.detail,
            "notes": self.notes,
        }


# --------------------------------------------------------------------------- #
# Reference distribution
# --------------------------------------------------------------------------- #
def build_reference(
    *,
    model_dir: str | Path = "artifacts/model_calibrated",
    split_path: str | Path = "data/processed/validation.parquet",
    out_path: str | Path = REFERENCE_DIR / "prediction_reference.json",
) -> dict[str, Any]:
    """Score the validation split with the frozen artifact and freeze the result.

    Committed as an artifact so the reference is fixed at build time. Recomputing
    it from live traffic would let the reference follow production, which is
    exactly the failure mode that hides drift.
    """
    from churn.api.inference import ServingBundle

    bundle = ServingBundle.load(Path(model_dir))
    frame = pd.read_parquet(split_path).drop(columns=["Churn"])
    scores = bundle.score(frame)

    probabilities = np.asarray(scores.probabilities, dtype="float64")
    bands = list(scores.bands)
    classes = np.asarray(scores.classes, dtype="int64")

    histogram = _histogram(probabilities)
    band_labels = ["Low", "Medium", "High"]
    band_counts = np.array([bands.count(label) for label in band_labels], dtype="float64")

    payload = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "model_version": bundle.model_version,
        "decision_threshold": bundle.threshold,
        "source_split": Path(split_path).stem,
        "rows": int(len(probabilities)),
        "probability_bins": list(PROBABILITY_BINS),
        "probability_histogram": [float(x) for x in histogram],
        "mean_probability": float(probabilities.mean()),
        "positive_rate": float(classes.mean()),
        "band_labels": band_labels,
        "band_counts": [float(x) for x in band_counts],
        "notes": [
            "Generated by scoring the validation split with the frozen calibrated artifact.",
            "The reference is committed so it cannot drift along with production.",
            "Contains no customer records: histogram counts and band counts only.",
        ],
    }

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    logger.info(
        "prediction reference written",
        extra={"path": str(out_path), "rows": payload["rows"]},
    )
    return payload


def load_reference(
    path: str | Path = REFERENCE_DIR / "prediction_reference.json",
) -> dict[str, Any]:
    candidate = Path(path)
    if not candidate.exists():
        raise FileNotFoundError(
            f"prediction reference not found at {candidate}; run "
            "`python -m churn.monitoring.prediction_drift --build-reference`"
        )
    return json.loads(candidate.read_text(encoding="utf-8"))


def _histogram(probabilities: np.ndarray) -> np.ndarray:
    edges = np.asarray(PROBABILITY_BINS, dtype="float64")
    counts, _ = np.histogram(probabilities, bins=edges)
    return counts.astype("float64")


# --------------------------------------------------------------------------- #
# Production side
# --------------------------------------------------------------------------- #
def read_production(
    session: Session, *, model_version: str, start: datetime, end: datetime
) -> tuple[np.ndarray, list[str], np.ndarray] | None:
    """Read probabilities, bands and classes for a window.

    Only the serving model version is read, matching the feature-side rule: a
    window must never blend two models' outputs into an average that describes
    neither.
    """
    rows = session.execute(
        select(
            Prediction.churn_probability,
            Prediction.risk_band,
            Prediction.predicted_class,
        ).where(
            Prediction.model_version == model_version,
            Prediction.created_at >= start,
            Prediction.created_at < end,
        )
    ).all()

    if not rows:
        return None

    probabilities = np.array([float(row[0]) for row in rows], dtype="float64")
    bands = [str(row[1]) for row in rows]
    classes = np.array([int(row[2]) for row in rows], dtype="int64")
    return probabilities, bands, classes


def compare(
    session: Session,
    *,
    reference: dict[str, Any],
    model_version: str,
    min_observations: int = 400,
    window_days: int = 7,
    now: datetime | None = None,
    psi_threshold: float = 0.10,
    js_threshold: float = 0.10,
) -> PredictionDriftResult:
    """Compare production predictions against the frozen reference."""
    moment = now or datetime.now(timezone.utc)
    today = moment.astimezone(timezone.utc).replace(hour=0, minute=0, second=0, microsecond=0)
    start = today - timedelta(days=max(window_days - 1, 0))

    result = PredictionDriftResult(
        status="no_data",
        generated_at_utc=datetime.now(timezone.utc).isoformat(timespec="seconds"),
        model_version=model_version,
        min_observations=min_observations,
        window_start=start.isoformat(),
        window_end=moment.isoformat(),
        reference_mean_probability=float(reference.get("mean_probability", 0.0)),
        reference_positive_rate=float(reference.get("positive_rate", 0.0)),
        notes=[
            "Prediction drift describes the OUTPUT distribution, not correctness.",
            "No ground-truth outcomes are observed, so performance drift is not measured.",
            "Reference generated by the frozen artifact on the validation split.",
        ],
    )

    data = read_production(session, model_version=model_version, start=start, end=moment)
    if data is None:
        result.detail = "No predictions recorded for this model version in the window."
        return result

    probabilities, bands, classes = data
    result.observations = int(len(probabilities))
    result.production_mean_probability = float(probabilities.mean())
    result.production_positive_rate = float(classes.mean())

    if result.observations < min_observations:
        result.status = "insufficient_data"
        result.detail = (
            f"{result.observations} prediction(s) is below the {min_observations} "
            "minimum; prediction drift is not reported at this sample size."
        )
        return result

    result.status = "ok"

    reference_hist = np.array(reference["probability_histogram"], dtype="float64")
    production_hist = _histogram(probabilities)

    result.probability_psi = population_stability_index(production_hist, reference_hist)
    result.probability_js = jensen_shannon_distance(production_hist, reference_hist)
    result.probability_p_value = chi_square_p_value(production_hist, reference_hist)

    band_labels = list(reference["band_labels"])
    reference_bands = np.array(reference["band_counts"], dtype="float64")
    production_bands = np.array([bands.count(label) for label in band_labels], dtype="float64")
    result.band_js = jensen_shannon_distance(production_bands, reference_bands)
    result.band_p_value = chi_square_p_value(production_bands, reference_bands)

    # Two comparisons, so FDR applies here too — it is easy to forget on a small
    # family, and a family of two doubles the chance of a spurious call.
    flags, _ = benjamini_hochberg([result.probability_p_value, result.band_p_value], alpha=0.10)
    probability_significant, band_significant = flags

    probability_moved = result.probability_psi > psi_threshold and probability_significant
    band_moved = result.band_js > js_threshold and band_significant
    result.drifted = bool(probability_moved or band_moved)

    if result.drifted:
        parts = []
        if probability_moved:
            parts.append(
                f"probability distribution moved (PSI {result.probability_psi:.3f}, "
                f"mean {result.reference_mean_probability:.3f} -> "
                f"{result.production_mean_probability:.3f})"
            )
        if band_moved:
            parts.append(f"risk-band mix moved (JS {result.band_js:.3f})")
        result.detail = "; ".join(parts)
    else:
        result.detail = "No material shift in the prediction distribution."

    return result


def positive_rate_delta(result: PredictionDriftResult) -> float:
    """Convenience accessor used by the report renderer."""
    return result.production_positive_rate - result.reference_positive_rate


def main(argv: list[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-reference", action="store_true")
    parser.add_argument("--model-dir", default="artifacts/model_calibrated")
    parser.add_argument("--split", default="data/processed/validation.parquet")
    parser.add_argument("--out", default=str(REFERENCE_DIR / "prediction_reference.json"))
    args = parser.parse_args(argv)

    if not args.build_reference:
        parser.error("nothing to do; pass --build-reference")

    payload = build_reference(model_dir=args.model_dir, split_path=args.split, out_path=args.out)
    print(f"rows            : {payload['rows']}")
    print(f"model version   : {payload['model_version']}")
    print(f"mean probability: {payload['mean_probability']:.6f}")
    print(f"positive rate   : {payload['positive_rate']:.6f}")
    print(f"band counts     : {payload['band_counts']}")
    print(f"written to      : {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
